"""S3 is a hybrid: the AI proposes the mapping, but the reconciliation checks are
generated by code from that mapping, and the AI's own proposed checks are ignored."""
import json
import sys
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace
from unittest import mock

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from amt import cli  # noqa: E402
from amt.connectors.sources import SQLiteSource  # noqa: E402
from amt.connectors.targets import LocalTarget  # noqa: E402
from amt.reconcile import schema_aware_rules  # noqa: E402
from eval import corpus  # noqa: E402

# An AI answer for ecommerce.orders whose own checks include a column-less
# null_count, the mistake the local model made most often in the evaluation.
ANSWER = json.dumps({
    "columns": [
        {"source": "id", "target": "id", "target_type": "int64", "transform": "none", "null_handling": "preserve"},
        {"source": "customer_id", "target": "customer_id", "target_type": "int64", "transform": "none", "null_handling": "preserve"},
        {"source": "placed_at", "target": "placed_at", "target_type": "timestamp_tz", "transform": "tz_to_utc", "null_handling": "preserve"},
        {"source": "status", "target": "status", "target_type": "string", "transform": "none", "null_handling": "preserve"},
        {"source": "total_amount", "target": "total_amount", "target_type": "decimal(18,2)", "transform": "none", "null_handling": "preserve"},
        {"source": "gift_wrap", "target": "gift_wrap", "target_type": "bool", "transform": "none", "null_handling": "preserve"},
    ],
    "rules": [{"kind": "null_count", "column": None, "tolerance": 0},
              {"kind": "pk_unique", "column": "customer_id", "tolerance": 0}],
})


class StubAI:
    calls = input_tokens = output_tokens = 0
    model = "stub"

    def complete(self, *a, **k):
        return ANSWER


class HybridS3Test(unittest.TestCase):
    def test_s3_uses_code_generated_checks(self):
        work = Path(tempfile.mkdtemp())
        db = work / "ecommerce.db"
        corpus.build_schema_db("ecommerce", db, 7)
        ts = next(t for s, t in corpus.all_tables() if s == "ecommerce" and t.name == "orders")
        spec = corpus.target_spec(ts, "")
        with mock.patch("amt.llm.make_client", lambda *a, **k: StubAI()):
            agent = cli.build_agent(SimpleNamespace(strategy="s3", provider="ollama", model=None, precedents=None))
        rep = agent.run(SQLiteSource(str(db)), "orders", spec, LocalTarget(str(work / "lake")))
        self.assertIsNone(rep.error)
        self.assertEqual(rep.summary["status"], "PASS")       # no false alarm on clean data
        used = sorted((r.kind, r.column or "") for r in rep.plan.rules)
        code = sorted((r.kind, r.column or "") for r in schema_aware_rules(rep.plan.table, rep.plan.mapping, spec))
        self.assertEqual(used, code)
        self.assertIn(("sum_exact", "total_amount"), used)    # catches rounded decimals
        self.assertIn(("timestamp_exact", "placed_at"), used)  # catches time-zone shifts

    def test_dashboard_s3_is_hybrid(self):
        from amt.ui import jobs
        with mock.patch("amt.llm.make_client", lambda *a, **k: StubAI()), \
             mock.patch.object(jobs, "_precedents", lambda: __import__("amt.retriever", fromlist=["x"]).PrecedentStore()), \
             mock.patch.dict(jobs._W, {"work": Path(tempfile.mkdtemp())}):
            agent = jobs._agent("s3", "demo:ecommerce")
        self.assertEqual(agent.rule_mode, "schema_aware")


if __name__ == "__main__":
    unittest.main()
